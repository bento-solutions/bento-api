package com.bento.crm.invoice.controller;

import com.bento.crm.common.dto.PageResponse;
import com.bento.crm.invoice.dto.InvoiceResponse;
import com.bento.crm.invoice.dto.RecurringInvoiceRequest;
import com.bento.crm.invoice.dto.RecurringInvoiceResponse;
import com.bento.crm.invoice.service.InvoiceMailer;
import com.bento.crm.invoice.service.RecurringInvoiceService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.data.domain.Pageable;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.*;

import java.util.List;
import java.util.UUID;

@RestController
@RequestMapping("/recurring-invoices")
@RequiredArgsConstructor
@Tag(name = "Recurring invoices", description = "Templates that generate an invoice every period")
public class RecurringInvoiceController {

    private final RecurringInvoiceService recurringInvoiceService;
    private final InvoiceMailer invoiceMailer;

    @PostMapping
    @PreAuthorize("hasAuthority('INVOICES_CREATE')")
    @Operation(summary = "Create recurring invoice")
    public ResponseEntity<RecurringInvoiceResponse> create(@Valid @RequestBody RecurringInvoiceRequest request) {
        return ResponseEntity.status(HttpStatus.CREATED)
                .body(recurringInvoiceService.toResponse(recurringInvoiceService.create(request)));
    }

    @GetMapping
    @PreAuthorize("hasAuthority('INVOICES_READ')")
    @Operation(summary = "List recurring invoices")
    public ResponseEntity<PageResponse<RecurringInvoiceResponse>> list(Pageable pageable) {
        return ResponseEntity.ok(PageResponse.fromPage(
                recurringInvoiceService.list(pageable).map(recurringInvoiceService::toResponse)));
    }

    @GetMapping("/{id}")
    @PreAuthorize("hasAuthority('INVOICES_READ')")
    @Operation(summary = "Get recurring invoice")
    public ResponseEntity<RecurringInvoiceResponse> get(@PathVariable UUID id) {
        return ResponseEntity.ok(recurringInvoiceService.toResponse(recurringInvoiceService.get(id)));
    }

    @GetMapping("/{id}/invoices")
    @PreAuthorize("hasAuthority('INVOICES_READ')")
    @Operation(summary = "Invoices generated by a recurring invoice", description = "Newest first")
    public ResponseEntity<List<InvoiceResponse>> invoices(@PathVariable UUID id) {
        return ResponseEntity.ok(recurringInvoiceService.invoicesOf(id).stream().map(InvoiceResponse::fromEntity).toList());
    }

    @PatchMapping("/{id}")
    @PreAuthorize("hasAuthority('INVOICES_WRITE')")
    @Operation(summary = "Update recurring invoice",
            description = "Frequency and start date can only change before the first invoice is generated")
    public ResponseEntity<RecurringInvoiceResponse> update(@PathVariable UUID id,
                                                           @Valid @RequestBody RecurringInvoiceRequest request) {
        return ResponseEntity.ok(recurringInvoiceService.toResponse(recurringInvoiceService.update(id, request)));
    }

    @PostMapping("/{id}/pause")
    @PreAuthorize("hasAuthority('INVOICES_WRITE')")
    @Operation(summary = "Pause recurring invoice")
    public ResponseEntity<RecurringInvoiceResponse> pause(@PathVariable UUID id) {
        return ResponseEntity.ok(recurringInvoiceService.toResponse(recurringInvoiceService.pause(id)));
    }

    @PostMapping("/{id}/resume")
    @PreAuthorize("hasAuthority('INVOICES_WRITE')")
    @Operation(summary = "Resume recurring invoice", description = "Periods that passed while paused are skipped")
    public ResponseEntity<RecurringInvoiceResponse> resume(@PathVariable UUID id) {
        return ResponseEntity.ok(recurringInvoiceService.toResponse(recurringInvoiceService.resume(id)));
    }

    @PostMapping("/{id}/generate")
    @PreAuthorize("hasAuthority('INVOICES_CREATE')")
    @Operation(summary = "Generate the next invoice now",
            description = "Bills the next period today and moves the schedule on by one period")
    public ResponseEntity<InvoiceResponse> generateNow(@PathVariable UUID id) {
        RecurringInvoiceService.Generated generated = recurringInvoiceService.generateNow(id);
        if (generated.send()) {
            invoiceMailer.sendInvoice(generated.invoice());
        }
        return ResponseEntity.status(HttpStatus.CREATED).body(InvoiceResponse.fromEntity(generated.invoice()));
    }

    @DeleteMapping("/{id}")
    @PreAuthorize("hasAuthority('INVOICES_DELETE')")
    @Operation(summary = "Delete recurring invoice", description = "Invoices already generated are kept")
    public ResponseEntity<Void> delete(@PathVariable UUID id) {
        recurringInvoiceService.delete(id);
        return ResponseEntity.noContent().build();
    }
}
